#!/usr/bin/env python3

from glob import glob
import os

HEAD_SIZES_KQ = [40, 64, 72, 80, 96, 112, 128, 256, 512, 576]

TYPES_KV = ["GGML_TYPE_F16", "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0", "GGML_TYPE_BF16", "GGML_TYPE_TQ3_0"]

SOURCE_FATTN_TILE = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-tile.cuh"

DECL_FATTN_TILE_CASE({head_size_kq}, {head_size_v});
"""

SOURCE_FATTN_VEC = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-vec.cuh"

DECL_FATTN_VEC_CASE( 64, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(128, {type_k}, {type_v});
DECL_FATTN_VEC_CASE(256, {type_k}, {type_v});
"""

SOURCE_FATTN_MMA_START = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../fattn-mma-f16.cuh"

"""

SOURCE_FATTN_MMA_CASE = "DECL_FATTN_MMA_F16_CASE({head_size_kq}, {head_size_v}, {ncols1}, {ncols2});\n"

TYPES_MMQ = [
    "GGML_TYPE_Q4_0", "GGML_TYPE_Q4_1", "GGML_TYPE_Q5_0", "GGML_TYPE_Q5_1", "GGML_TYPE_Q8_0",
    "GGML_TYPE_Q4_0_ROCMFP4_FAST", "GGML_TYPE_Q2_0_ROCMFP2", "GGML_TYPE_Q2_1_ROCMFP2_MIX", "GGML_TYPE_Q3_0_ROCMFPX", "GGML_TYPE_Q3_1_ROCMFP3_MIX",
    "GGML_TYPE_Q2_K", "GGML_TYPE_Q3_K", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K", "GGML_TYPE_Q6_K",
    "GGML_TYPE_IQ2_XXS", "GGML_TYPE_IQ2_XS", "GGML_TYPE_IQ2_S", "GGML_TYPE_IQ3_XXS", "GGML_TYPE_IQ3_S",
    "GGML_TYPE_IQ1_S", "GGML_TYPE_IQ4_NL", "GGML_TYPE_IQ4_XS", "GGML_TYPE_MXFP4", "GGML_TYPE_NVFP4"
]

SOURCE_MMQ = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

{guard}#include "../mmq.cuh"

DECL_MMQ_CASE({type});
"""

SOURCE_MMF = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.

#include "../mmf.cuh"

DECL_MMF_CASE({type});
"""


def get_short_name(long_quant_name):
    return long_quant_name.replace("GGML_TYPE_", "").lower()


for filename in glob("*.cu"):
    os.remove(filename)

for head_size_kq in HEAD_SIZES_KQ:
    head_size_v = head_size_kq if head_size_kq != 576 else 512
    with open(f"fattn-tile-instance-dkq{head_size_kq}-dv{head_size_v}.cu", "w") as f:
        f.write(SOURCE_FATTN_TILE.format(head_size_kq=head_size_kq, head_size_v=head_size_v))

for type_k in TYPES_KV:
    for type_v in TYPES_KV:
        with open(f"fattn-vec-instance-{get_short_name(type_k)}-{get_short_name(type_v)}.cu", "w") as f:
            f.write(SOURCE_FATTN_VEC.format(type_k=type_k, type_v=type_v))

for ncols in [8, 16, 32, 64]:
    for ncols2 in [1, 2, 4, 8, 16, 32]:
        if ncols2 > ncols:
            continue
        ncols1 = ncols // ncols2
        with open(f"fattn-mma-f16-instance-ncols1_{ncols1}-ncols2_{ncols2}.cu", "w") as f:
            f.write(SOURCE_FATTN_MMA_START)

            for head_size_kq in HEAD_SIZES_KQ:
                if head_size_kq == 40:
                    continue
                if head_size_kq == 72:
                    continue
                if head_size_kq == 512 and ncols2 not in (4, 8):
                    continue
                if head_size_kq != 576 and ncols2 in (16, 32):
                    continue
                if head_size_kq == 576 and ncols2 not in (4, 16, 32):
                    continue
                head_size_v = head_size_kq if head_size_kq != 576 else 512
                f.write(SOURCE_FATTN_MMA_CASE.format(ncols1=ncols1, ncols2=ncols2, head_size_kq=head_size_kq, head_size_v=head_size_v))

for type in TYPES_MMQ:
    with open(f"mmq-instance-{get_short_name(type)}.cu", "w") as f:
        guard = ""
        if type in {
            "GGML_TYPE_Q4_0_ROCMFP4_FAST",
            "GGML_TYPE_Q2_0_ROCMFP2",
            "GGML_TYPE_Q2_1_ROCMFP2_MIX",
            "GGML_TYPE_Q3_0_ROCMFPX",
            "GGML_TYPE_Q3_1_ROCMFP3_MIX",
            # Dense hybrid (Qwen3.5/3.8) verify widths N<=16 on gfx1201: the
            # 128-row tile leaves a 5120-row projection with only 40 blocks;
            # 64x64/4-warp tiles measured +12-23% on those shapes (mmq_probe).
            "GGML_TYPE_IQ4_XS",
            "GGML_TYPE_Q4_K",
            "GGML_TYPE_Q5_K",
            "GGML_TYPE_Q6_K",
            "GGML_TYPE_Q8_0",
        }:
            guard = "#define GGML_CUDA_MMQ_SMALL_TILE 1\n"
            # Dense hybrid targets take the small tile on RDNA4 only: the
            # measurement is gfx1201 and the big-tile twin dispatch that
            # covers wide N is RDNA4-only. ROCmFPX keeps it on RDNA3 too.
            if type in {
                "GGML_TYPE_IQ4_XS", "GGML_TYPE_Q5_K",
                "GGML_TYPE_Q6_K", "GGML_TYPE_Q8_0",
            }:
                guard += "#define GGML_CUDA_MMQ_SMALL_TILE_RDNA4_ONLY 1\n"
        if type == "GGML_TYPE_Q4_K":
            guard = "#define LUCEBOX_RDNA_MMQ_Y 64\n"
        f.write(SOURCE_MMQ.format(type=type, guard=guard))

BIG_TILE_TYPES = [
    "GGML_TYPE_IQ4_XS", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K",
    "GGML_TYPE_Q6_K", "GGML_TYPE_Q8_0",
]

SOURCE_MMQ_BIG = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.
// Big-tile (128x128) twin of mmq-instance-{name}.cu: no tile macro, so mmq.cuh
// compiles with the upstream RDNA default shape. Namespaced to coexist with
// the small-tile instance (see mmq_big.h).

#include "../common.cuh"
#include "../vecdotq.cuh"
#include "../mma.cuh"

#include <climits>
#include <cstdint>

namespace lucebox_mmq_big {{
#include "../mmq.cuh"

DECL_MMQ_CASE({type});
}}  // namespace lucebox_mmq_big

#include "../mmq_big.h"

void mul_mat_q_case_big_{name}(ggml_backend_cuda_context & ctx, const void * args, cudaStream_t stream) {{
    lucebox_mmq_big::mul_mat_q_case<{type}>(
        ctx, *(const lucebox_mmq_big::mmq_args *) args, stream);
}}
"""

for type in BIG_TILE_TYPES:
    name = type.replace("GGML_TYPE_", "").lower()
    with open(f"mmq-instance-{name}-big.cu", "w") as f:
        f.write(SOURCE_MMQ_BIG.format(type=type, name=name))

# MMQ tile twins (mmq_tile_twins.h): narrower row tiles that mmq.cu picks on
# RDNA4 for 16 or fewer columns, and for the 17-48 column calls its measured
# policy assigns. Only x-tiles 16, 32 and 48 and their tiled launch are
# compiled (no stream-k fixup), with device code for RDNA4 targets only. The
# 64-row twins also compile the prefetching kernel (launch_mul_mat_q_pf),
# which serves their 17-48 column calls.
TILE_TWINS = {
    # 64-row/4-warp for IQ3_S and IQ3_XXS, whose parent instances keep the
    # 128-row/8-warp RDNA tile (Q3_K, IQ2_S, IQ2_XS and Q2_K measured slower
    # on it than on their parents).
    64: {
        "macros": "#define GGML_CUDA_MMQ_SMALL_TILE 1\n"
                  "#define GGML_CUDA_MMQ_SMALL_TILE_RDNA4_ONLY 1\n",
        "types": [
            "GGML_TYPE_IQ3_S", "GGML_TYPE_IQ3_XXS",
            # 17-48 column calls only (the x16 gate does not use them).
            "GGML_TYPE_IQ4_XS", "GGML_TYPE_Q5_K", "GGML_TYPE_Q3_K", "GGML_TYPE_IQ2_S",
        ],
    },
    # 32-row/2-warp for outputs of <= 6144 rows, for the
    # types the Qwen3.8 UD-IQ4_XS target has on such outputs.
    32: {
        "macros": "#define GGML_CUDA_MMQ_SMALL_TILE 1\n"
                  "#define GGML_CUDA_MMQ_SMALL_TILE_RDNA4_ONLY 1\n"
                  "#define GGML_CUDA_MMQ_SMALL_TILE_ROWS 32\n",
        "types": [
            "GGML_TYPE_IQ4_XS", "GGML_TYPE_Q4_K", "GGML_TYPE_Q5_K",
            "GGML_TYPE_Q6_K", "GGML_TYPE_Q8_0", "GGML_TYPE_IQ3_S",
            "GGML_TYPE_IQ3_XXS",
            # 17-48 column calls only (the x16 gate does not use them).
            "GGML_TYPE_Q3_K", "GGML_TYPE_IQ2_S",
        ],
    },
}

SOURCE_MMQ_TWIN = """// This file has been autogenerated by generate_cu_files.py, do not edit manually.
// {rows}-row/{warps}-warp twin of mmq-instance-{name}.cu: MMQ calls of 16 or
// fewer columns on RDNA4 (x-tile 16), and the 17-48 column calls mmq.cu
// assigns to it (x-tile 16, 32 or 48). Namespaced to coexist with the parent
// instance (see mmq_tile_twins.h).

#include "../mmq_tile_twins.h"

#if defined(GGML_USE_HIP)
#include "../vecdotq.cuh"
#include "../mma.cuh"

#include <climits>
#include <cstdint>
#include <cstring>
#include <type_traits>

#define GGML_CUDA_MMQ_TILE_TWIN 1
{macros}
namespace luce_mmq_twin_rows{rows} {{
#include "../mmq.cuh"
}}  // namespace luce_mmq_twin_rows{rows}

bool mul_mat_q_case_rows{rows}_{name}(ggml_backend_cuda_context & ctx, const void * args, cudaStream_t stream, int mmq_x) {{
    // `args` points at the caller's ::mmq_args. This namespace's mmq_args is
    // textually the same struct but a distinct type, so copy the bytes into
    // an object of this type rather than read the caller's through it.
    using twin_args_t = luce_mmq_twin_rows{rows}::mmq_args;
    static_assert(std::is_trivially_copyable<twin_args_t>::value, "mmq_args must stay trivially copyable");
    twin_args_t twin_args;
    std::memcpy(&twin_args, args, sizeof(twin_args));
    return luce_mmq_twin_rows{rows}::mul_mat_q_case_twin<{type}, {prefetch}>(ctx, twin_args, stream, mmq_x);
}}
#else
bool mul_mat_q_case_rows{rows}_{name}(ggml_backend_cuda_context &, const void *, cudaStream_t, int) {{
    return false;
}}
#endif // defined(GGML_USE_HIP)
"""

for rows, twin in TILE_TWINS.items():
    for type in twin["types"]:
        name = type.replace("GGML_TYPE_", "").lower()
        with open(f"mmq-instance-{name}-rows{rows}.cu", "w") as f:
            f.write(SOURCE_MMQ_TWIN.format(
                rows=rows, warps=rows // 16, name=name, type=type,
                macros=twin["macros"], prefetch="true" if rows == 64 else "false"))

for type in range(1, 17):
    with open(f"mmf-instance-ncols_{type}.cu", "w") as f:
        f.write(SOURCE_MMF.format(type=type))
